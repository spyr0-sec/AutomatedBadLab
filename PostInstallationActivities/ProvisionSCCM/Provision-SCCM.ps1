# Provisions the site with all AD devices, a selection of users and a software catalogue
param(
    [string]$SiteCode = 'LD1',
    [int]$UserCount = 20
)

# Logger function
Function Write-Log {
    param (
        [Parameter(Mandatory = $true)]
        [string]$Message,

        [ValidateSet("Default", "Informational", "Warning")]
        [string]$Level = "Default"
    )

    $Timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"

    switch ($Level) {
        "Default"       { $LogMessage = "$Timestamp - [+] $Message" }
        "Informational" { $LogMessage = "$Timestamp -   [+] $Message" }
        "Warning"       { $LogMessage = "$Timestamp -   [!] $Message" }
    }

    $LogMessage | Out-File -FilePath "C:\AutomatedBadLab.log" -Append
}

# Import the Configuration Manager module and connect to the site
Import-Module ConfigurationManager

if (-not (Get-PSDrive -Name $SiteCode -ErrorAction SilentlyContinue)) {
    New-PSDrive -Name $SiteCode -PSProvider 'AdminUI' -Root $SiteCode
}

Push-Location "$($SiteCode):\"

try {
    Write-Log -Message "Provisioning Configuration Manager Site $SiteCode"

    # Import all real AD computer accounts into the All ABL Devices collection, excluding those generated by AutomatedBadLab
    $DeviceCollection = Get-CMDeviceCollection -Name 'All ABL Devices' -ErrorAction SilentlyContinue
    if (-not $DeviceCollection) { $DeviceCollection = New-CMDeviceCollection -Name 'All ABL Devices' -LimitingCollectionId 'SMS00001' -RefreshType Continuous }

    $Searcher = [ADSISearcher]'(&(objectClass=computer)(!(description=Computer generated by AutomatedBadLab*)))'
    $Searcher.PageSize = 1000
    $Searcher.PropertiesToLoad.AddRange(('name','objectGuid'))

    foreach ($Device in $Searcher.FindAll()) {
        $DeviceName = $Device.Properties['name'][0]
        $DeviceGuid = [Guid]$Device.Properties['objectguid'][0]

        try {
            Import-CMComputerInformation -ComputerName $DeviceName -SMBiosGuid $DeviceGuid -CollectionName 'All ABL Devices' -MergeIfExist
            Write-Log -Message "$DeviceName imported into All ABL Devices" -Level Informational
        } catch {
            Write-Log -Message "$DeviceName could not be imported: $($_.Exception.Message)" -Level Warning
        }
    }

    # Discover all AD users and add a random selection to the Selected Users collection
    try {
        $Container = "LDAP://DC=" + ($env:USERDNSDOMAIN -replace '\.',',DC=')
        Set-CMDiscoveryMethod -ActiveDirectoryUserDiscovery -Enabled $true -AddActiveDirectoryContainer $Container
    } catch {
        Write-Log -Message "User discovery could not be enabled: $($_.Exception.Message)" -Level Warning
    }

    $Attempts = 0
    while (((@(Get-CMUser).Count) -lt $UserCount) -and ($Attempts -lt 40)) {
        Start-Sleep -Seconds 15
        $Attempts++
    }

    Write-Log -Message "User discovery discovered $(@(Get-CMUser).Count) users"

    $UserCollection = Get-CMUserCollection -Name 'Selected Users' -ErrorAction SilentlyContinue
    if (-not $UserCollection) { $UserCollection = New-CMUserCollection -Name 'Selected Users' -LimitingCollectionId 'SMS00002' }

    # Only populate the collection when empty so reruns keep the original selection
    if (@(Get-CMUser -CollectionId $UserCollection.CollectionID).Count -eq 0) {
        foreach ($User in (Get-CMUser | Get-Random -Count $UserCount)) {
            try {
                Add-CMUserCollectionDirectMembershipRule -CollectionId $UserCollection.CollectionID -ResourceId $User.ResourceID
                Write-Log -Message "$($User.FullUserName) added to Selected Users" -Level Informational
            } catch {
                Write-Log -Message "$($User.FullUserName) could not be added: $($_.Exception.Message)" -Level Warning
            }
        }
    }

    # Create and deploy the software catalogue
    $Software = @(
        @{ Name = 'Notepad++'; Publisher = 'Notepad++ Team'; Version = '8.7.9'
           Url = 'https://github.com/notepad-plus-plus/notepad-plus-plus/releases/download/v8.7.9/npp.8.7.9.Installer.x64.exe'
           Type = 'Script'; InstallCommand = 'npp.8.7.9.Installer.x64.exe /S'
           Detection = 'if (Test-Path "C:\Program Files\Notepad++\notepad++.exe") { Write-Output "Installed" }' }
        @{ Name = '7-Zip'; Publisher = 'Igor Pavlov'; Version = '24.08'
           Url = 'https://www.7-zip.org/a/7z2408-x64.msi'
           Type = 'Msi' }
    )

    if (-not (Get-SmbShare -Name 'Source$' -ErrorAction SilentlyContinue)) {
        New-Item -ItemType Directory -Path 'C:\Source\Apps' -Force
        New-SmbShare -Name 'Source$' -Path 'C:\Source' -ReadAccess 'Authenticated Users'
    }

    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

    foreach ($Application in $Software) {
        $DownloadPath = "C:\Source\Apps\$($Application.Name)"
        $SharePath = "\\$env:COMPUTERNAME\Source$\Apps\$($Application.Name)"
        $FileName = Split-Path $Application.Url -Leaf

        try {
            New-Item -ItemType Directory -Path $DownloadPath -Force
            Invoke-WebRequest -Uri $Application.Url -OutFile "$DownloadPath\$FileName"

            if (-not (Get-CMApplication -Name $Application.Name -ErrorAction SilentlyContinue)) {
                New-CMApplication -Name $Application.Name -Publisher $Application.Publisher -SoftwareVersion $Application.Version
            }

            if (-not (Get-CMDeploymentType -ApplicationName $Application.Name -ErrorAction SilentlyContinue)) {
                if ($Application.Type -eq 'Msi') {
                    Add-CMDeploymentType -ApplicationName $Application.Name -DeploymentTypeName "$($Application.Name) $($Application.Version) x64" -MsiInstaller -AutoIdentifyFromInstallationFile -ContentLocation "$SharePath\$FileName" -ForceForUnknownPublisher $true
                } else {
                    Add-CMScriptDeploymentType -ApplicationName $Application.Name -DeploymentTypeName "$($Application.Name) $($Application.Version) x64" -ScriptLanguage 'PowerShell' -ScriptText $Application.Detection -InstallCommand $Application.InstallCommand -ContentLocation $SharePath
                }
            }

            if (-not (Get-CMDeployment -ErrorAction SilentlyContinue | Where-Object ApplicationName -eq $Application.Name)) {
                New-CMApplicationDeployment -Name $Application.Name -CollectionId $DeviceCollection.CollectionID -DeployPurpose Required -DeadlineDateTime (Get-Date).AddMinutes(30) -TimeBaseOn LocalTime

                try { Start-CMContentDistribution -ApplicationName $Application.Name -DistributionPointName "$env:COMPUTERNAME.$env:USERDNSDOMAIN" -ErrorAction Stop } catch { Write-Log -Message "$($Application.Name) content already distributed" -Level Informational }
            }

            Write-Log -Message "$($Application.Name) created and deployed to All ABL Devices" -Level Informational
        } catch {
            Write-Log -Message "$($Application.Name) could not be created or deployed: $($_.Exception.Message)" -Level Warning
        }
    }

} finally {
    Pop-Location
}
